#!/usr/bin/env bash
# WhiteSur's application icons into icons/WhiteSur, from one pinned release.
#
# Only what the shell draws: the full-colour app icons (src/apps/scalable)
# and the names WhiteSur gives them besides (links/apps/scalable, links to
# those same files), with the theme's licence and authors. The dark variant's
# app icons are these same files, so there is one copy. Nothing of WhiteSur's
# own installer is run.
#
# Writes icons/WhiteSur/names.js, the index qml/icons.js reads to tell, before
# loading anything, whether WhiteSur has an icon for a name.
#
# Run from anywhere; commit what it changes. To move to another release, set
# TAG and SHA256 to it.
set -euo pipefail

TAG=2026-09-10
SHA256=406c9cd59705583f1754b0eaca96cc48bafda042b88ef143f16d8ae1820ecd95
URL="https://github.com/vinceliuice/WhiteSur-icon-theme/archive/refs/tags/$TAG.tar.gz"

here=$(cd "$(dirname "$0")/.." && pwd)
out="$here/icons/WhiteSur"
work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT

curl -fsSL -o "$work/whitesur.tar.gz" "$URL"
echo "$SHA256  $work/whitesur.tar.gz" | sha256sum -c --quiet -
tar -xzf "$work/whitesur.tar.gz" -C "$work"
src="$work/WhiteSur-icon-theme-$TAG"

rm -rf "$out"
mkdir -p "$out/apps/scalable"
cp -a "$src"/src/apps/scalable/. "$out/apps/scalable/"
cp -a "$src"/links/apps/scalable/. "$out/apps/scalable/"
# A name linked to something outside this one directory has nothing to point
# at here.
find "$out/apps/scalable" -xtype l -delete
cp "$src/COPYING" "$src/AUTHORS" "$out/"

{
    echo ".pragma library"
    echo "// Generated by tools/update-whitesur.sh from WhiteSur $TAG: every"
    echo "// application icon name it has. Do not edit."
    printf 'var names = {'
    find "$out/apps/scalable" -maxdepth 1 -name '*.svg' -printf '%f\n' | sed 's/\.svg$//' | LC_ALL=C sort \
        | awk 'BEGIN { first = 1 } { gsub(/\\/, "\\\\"); gsub(/"/, "\\\""); printf "%s\"%s\":1", (first ? "" : ","), $0; first = 0 }'
    echo '}'
} > "$out/names.js"

cat > "$out/README.md" <<EOF
# WhiteSur application icons

From [WhiteSur icon theme](https://github.com/vinceliuice/WhiteSur-icon-theme)
release \`$TAG\`, by Vince Liuice and its contributors (see \`AUTHORS\`),
under the GNU General Public License version 3 (see \`COPYING\`). Only the
application icons, as \`tools/update-whitesur.sh\` takes them; not modified.
EOF

echo "WhiteSur $TAG: $(find "$out/apps/scalable" -name '*.svg' | wc -l) app icon names in $out"
